// Generate full episode lists with real pirate embed URLs
const enrichedCatalog = rawCatalog.map(anime => {
  const mal = anime.malId;
  const isMovie = anime.type === 'Movie';
  const totalEps = isMovie ? 1 : Math.min(anime.subEpisodes || 12, 24);
  const episodes = [];

  for (let i = 1; i <= totalEps; i++) {
    episodes.push({
      number: i,
      title: isMovie ? anime.title : `Episode ${i}`,
      duration: isMovie ? anime.duration : '24:00',
      thumbnail: anime.banner || anime.poster,
      embedUrl: `https://vidsrc.pm/embed/anime/${mal}/${i}`,
      megaCloudUrl: `https://multiembed.mov/?video_id=${mal}&ep=${i}&an=1`,
      twoEmbedUrl: `https://www.2embed.cc/embed/anime/${mal}/${i}`,
      vidsrcClassicUrl: `https://vidsrc.me/embed/anime?mal=${mal}&ep=${i}`
    });
  }

  return {
    ...anime,
    mal_id: Number(anime.malId),
    cover: anime.poster,
    episodes
  };
});

